using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.IO.Compression;
using System.Runtime.InteropServices;
using System.Security.Cryptography;
using System.Text.Json;

namespace SocketJack.Net {
    /// <summary>A verified, bounded snapshot of explicit public assets and precompressed representations.</summary>
    public sealed class HttpStaticAssets {
        private static readonly StringComparer FilePaths = RuntimeInformation.IsOSPlatform(OSPlatform.Windows)
            ? StringComparer.OrdinalIgnoreCase : StringComparer.Ordinal;
        private static readonly JsonSerializerOptions Json = new JsonSerializerOptions(JsonSerializerDefaults.Web);
        private readonly Dictionary<string, Asset> files = new Dictionary<string, Asset>(FilePaths);
        private readonly Dictionary<string, Asset> relativeFiles = new Dictionary<string, Asset>(StringComparer.Ordinal);

        private HttpStaticAssets() { }

        /// <summary>Loads assets generated by tools/HttpAssets. Register only files intended for public delivery.</summary>
        public static HttpStaticAssets Load(string publicRoot, string manifestPath, long maximumSnapshotBytes = 64 * 1024 * 1024) {
            if (maximumSnapshotBytes <= 0)
                throw new ArgumentOutOfRangeException(nameof(maximumSnapshotBytes));
            var root = Path.GetFullPath(publicRoot);
            if ((File.GetAttributes(root) & FileAttributes.ReparsePoint) != 0)
                throw new InvalidDataException("The public asset root cannot be a link.");
            var manifest = JsonSerializer.Deserialize<Manifest>(ReadBytes(manifestPath, 1024 * 1024), Json);
            if (manifest?.Version != 1 || manifest.Assets == null || manifest.Assets.Length > 4096)
                throw new InvalidDataException("Expected a version 1 public asset manifest.");

            var result = new HttpStaticAssets();
            var remaining = maximumSnapshotBytes;
            foreach (var entry in manifest.Assets) {
                var path = ConfinedPath(root, entry?.Path);
                var identity = ReadRepresentation(path, entry.Sha256, entry.Length, ref remaining);
                var asset = new Asset(identity);
                if (entry.Encodings != null) {
                    foreach (var pair in entry.Encodings) {
                        var suffix = pair.Key == "br" ? ".br" : pair.Key == "gzip" ? ".gz" : null;
                        if (suffix == null || pair.Value?.Path != entry.Path + suffix)
                            throw new InvalidDataException("A compressed asset must use its identity file's supported sibling path.");
                        var encoded = ReadRepresentation(ConfinedPath(root, pair.Value.Path), pair.Value.Sha256, pair.Value.Length, ref remaining);
                        VerifyDecodedBytes(pair.Key, encoded.Bytes, identity.Bytes);
                        asset.Encodings.Add(pair.Key, encoded);
                    }
                }
                if (!result.files.TryAdd(path, asset) || !result.relativeFiles.TryAdd(entry.Path, asset))
                    throw new InvalidDataException("The manifest contains a duplicate asset.");
            }
            return result;
        }

        /// <summary>Returns the query token to append to the public URL of the given manifest asset.</summary>
        public string GetVersionQuery(string relativeAssetPath) {
            if (!relativeFiles.TryGetValue(relativeAssetPath, out var asset))
                throw new ArgumentException("The asset is not in the manifest.", nameof(relativeAssetPath));
            return asset.VersionQuery;
        }

        internal bool TryGet(string fullPath, string query, out Asset asset) {
            asset = null;
            return fullPath != null && query != null && files.TryGetValue(Path.GetFullPath(fullPath), out asset) && asset.VersionQuery == query;
        }

        private static string ConfinedPath(string root, string relative) {
            if (string.IsNullOrWhiteSpace(relative) || relative.IndexOfAny(new[] { '\\', ':', '\0', '?', '#' }) >= 0 ||
                Path.IsPathRooted(relative))
                throw new InvalidDataException("Expected a relative public asset path.");

            var path = root;
            foreach (var part in relative.Split('/')) {
                if (part.Length == 0 || part == "." || part == ".." || part != part.Trim())
                    throw new InvalidDataException("A public asset path contains an invalid component.");
                path = Path.Combine(path, part);
                if ((File.GetAttributes(path) & FileAttributes.ReparsePoint) != 0)
                    throw new InvalidDataException("Public asset paths cannot contain links.");
            }
            return Path.GetFullPath(path);
        }

        private static Representation ReadRepresentation(string path, string sha256, long length, ref long remaining) {
            if (length < 0 || length > remaining || sha256 == null || sha256.Length != 64)
                throw new InvalidDataException("A public asset exceeds the declared snapshot limits.");
            var bytes = ReadBytes(path, length);
            using var hash = SHA256.Create();
            var actual = BitConverter.ToString(hash.ComputeHash(bytes)).Replace("-", "").ToLowerInvariant();
            if (bytes.LongLength != length || !actual.Equals(sha256, StringComparison.Ordinal))
                throw new InvalidDataException("The public asset does not match its manifest hash and length.");
            remaining -= length;
            return new Representation(bytes, actual);
        }

        private static byte[] ReadBytes(string path, long maximum) {
            using var file = File.Open(path, FileMode.Open, FileAccess.Read, FileShare.Read);
            var length = file.Length;
            if (length > maximum || length > int.MaxValue)
                throw new InvalidDataException("A public asset exceeds its size limit.");
            var bytes = new byte[(int)length];
            for (int offset = 0; offset < bytes.Length;) {
                int read = file.Read(bytes, offset, bytes.Length - offset);
                if (read == 0) throw new EndOfStreamException();
                offset += read;
            }
            if (file.ReadByte() != -1) throw new InvalidDataException("The public asset changed during loading.");
            return bytes;
        }

        private static void VerifyDecodedBytes(string encoding, byte[] encoded, byte[] identity) {
            using var input = new MemoryStream(encoded, writable: false);
            using Stream decoder = encoding == "br"
                ? (Stream)new BrotliStream(input, CompressionMode.Decompress)
                : new GZipStream(input, CompressionMode.Decompress);
            var buffer = new byte[16 * 1024];
            for (int offset = 0; offset < identity.Length;) {
                int read = decoder.Read(buffer, 0, Math.Min(buffer.Length, identity.Length - offset));
                if (read == 0 || !buffer.AsSpan(0, read).SequenceEqual(identity.AsSpan(offset, read)))
                    throw new InvalidDataException("A compressed representation does not decode to its public asset.");
                offset += read;
            }
            if (decoder.ReadByte() != -1)
                throw new InvalidDataException("A compressed representation does not decode to its public asset.");
        }

        internal sealed class Asset {
            internal Asset(Representation identity) => Identity = identity;
            internal Representation Identity { get; }
            internal Dictionary<string, Representation> Encodings { get; } = new Dictionary<string, Representation>(StringComparer.Ordinal);
            internal string VersionQuery => "v=" + Identity.Sha256.Substring(0, 16);

            internal Representation Negotiate(string acceptEncoding, out string selectedEncoding) {
                selectedEncoding = null;
                var quality = new Dictionary<string, double>(StringComparer.OrdinalIgnoreCase);
                foreach (var item in (acceptEncoding ?? "").Split(',')) {
                    var fields = item.Split(';');
                    var name = fields[0].Trim();
                    if (name.Length == 0) continue;
                    double weight = 1;
                    for (int index = 1; index < fields.Length; index++) {
                        var field = fields[index].Trim();
                        if (!field.StartsWith("q=", StringComparison.OrdinalIgnoreCase)) continue;
                        if (!double.TryParse(field.Substring(2), NumberStyles.AllowDecimalPoint, CultureInfo.InvariantCulture, out weight) ||
                            weight < 0 || weight > 1 || double.IsNaN(weight)) weight = 0;
                    }
                    quality[name] = weight;
                }
                double wildcard = quality.TryGetValue("*", out var value) ? value : 0;
                double identityWeight = quality.TryGetValue("identity", out value) ? value :
                    quality.ContainsKey("*") && wildcard == 0 ? 0 : 1;
                var chosen = identityWeight > 0 ? Identity : null;
                double best = identityWeight;
                foreach (var encoding in new[] { "br", "gzip" }) {
                    if (!Encodings.TryGetValue(encoding, out var encoded)) continue;
                    var weight = quality.TryGetValue(encoding, out value) ? value : wildcard;
                    if (weight <= 0 || weight < best || (weight == best && selectedEncoding != null)) continue;
                    selectedEncoding = encoding;
                    chosen = encoded;
                    best = weight;
                }
                return chosen;
            }
        }

        internal sealed class Representation {
            internal Representation(byte[] bytes, string sha256) { Bytes = bytes; Sha256 = sha256; }
            internal byte[] Bytes { get; }
            internal string Sha256 { get; }
        }

        private sealed class Manifest {
            public int Version { get; set; }
            public Entry[] Assets { get; set; }
        }

        private class Variant {
            public string Path { get; set; }
            public string Sha256 { get; set; }
            public long Length { get; set; }
        }

        private sealed class Entry : Variant {
            public Dictionary<string, Variant> Encodings { get; set; }
        }
    }
}
